import fs from 'node:fs';import vm from 'node:vm';
const source=fs.readFileSync('flooring/smart-carpet-advisor-v1-lab.js','utf8');
new vm.Script(source);
const context={module:{exports:{}}};vm.createContext(context);vm.runInContext(source,context);
const a=context.module.exports,ok=(v,m)=>{if(!v)throw Error(m)};
ok(a.readOnly===true,'read-only contract');
ok(a.areaSF(10,'syd')===90,'square yards conversion');
ok(a.areaSF(90,'sf')===90,'square feet conversion');
ok(a.areaSF(90,'LF')===0,'unknown units must fail closed');
ok(a.widthFeet("12'")===12,'12 foot width');
ok(Math.abs(a.widthFeet("13' 2\"")-13.166666666666666)<.0001,'feet inches width');
ok(a.widthFeet("unknown")===0,'unknown width fail closed');
const row=(id,width,available,hold=true,other={})=>({id,kind:'Carpet Roll',name:'Dawn',colour:'Blue',width,quantity:available,available,selectable:true,hold:{known:hold},roll:id,lot:'DL-1',...other});
const items=[row('A',"12'",20),row('B',"12'",12),row('C',"15'",15,false),row('D',"",100),row('E',"12'",30,true,{colour:'Red'}),row('F',"12'",30,true,{selectable:false})];
const r=a.advise({style:'dawn',colour:'BLUE',quantity:20,unit:'syd',items});
ok(r.ok&&r.requestedSF===180,'request conversion');
ok(r.results.length===5,'exact product and colour');
ok(r.results[0].roll==='A'&&r.results[0].areaCandidate,'adequate area candidate');
ok(r.results[0].requiredLF===15,'LF calculation');
ok(!r.results[0].cutVerified,'area match must not certify cut');
ok(r.results.some(x=>x.roll==='B'&&x.reason==='INSUFFICIENT_AREA'),'short roll rejected');
ok(r.results.some(x=>x.roll==='C'&&x.reason==='HOLD_STATUS_UNVERIFIED'),'unknown holds flagged');
ok(r.results.some(x=>x.roll==='D'&&x.reason==='WIDTH_UNKNOWN'),'unknown width flagged');
ok(r.results.some(x=>x.roll==='F'&&x.reason==='UNAVAILABLE'),'inactive roll rejected');
ok(!/localStorage|\.insert\(|\.update\(|\.delete\(|fetch\(|\.rpc\(/.test(source),'no storage or network mutations');
const fields={style:'Dawn',colour:'Blue',quantity:20,unit:'syd'};
for(const missing of ['style','colour','quantity','unit']){
  const partial={...fields,[missing]:''};
  ok(!a.completionGate(partial,'blur').ready,'must not advise with missing '+missing);
}
ok(!a.completionGate(fields,'input').ready,'typing must not trigger popup');
ok(!a.completionGate(fields,'focus').ready,'focus must not trigger popup');
const complete=a.completionGate(fields,'blur');
ok(complete.ready&&complete.reason==='READY','complete committed line triggers advisor');
ok(a.sameRequest(fields,complete.requestKey),'unchanged request stays valid');
ok(a.sameRequest({...fields,quantity:180,unit:'sf'},complete.requestKey),'equivalent SF/SYD same request');
ok(!a.sameRequest({...fields,quantity:21},complete.requestKey),'quantity edit invalidates advice');
ok(!a.sameRequest({...fields,colour:'Red'},complete.requestKey),'colour edit invalidates advice');
ok(!a.sameRequest({...fields,style:'Other'},complete.requestKey),'style edit invalidates advice');
ok(!a.sameRequest({...fields,quantity:''},complete.requestKey),'cleared field invalidates advice');
const roll=(id,length,lot='DL-1',other={})=>row(id,"12'",length,true,{lot,...other});
const smaller=a.advise({style:'Dawn',colour:'Blue',quantity:80,unit:'sf',items:[roll('LONG',160),roll('NEAR',7),roll('SHORT',6),roll('MID',10)]});
ok(smaller.results[0].roll==='NEAR','smallest sufficient roll wins');
ok(smaller.results[0].estimatedRemainingSF===4,'leftover based on available size');
ok(smaller.results.find(x=>x.roll==='SHORT').reason==='INSUFFICIENT_AREA','undersized roll never recommended');
const pinned=a.advise({style:'Dawn',colour:'Blue',quantity:80,unit:'sf',dyelot:'DL-1',items:[roll('MATCH',8),roll('OTHER',7,'DL-2'),roll('UNKNOWN',7,'')]});
ok(pinned.results[0].roll==='MATCH','dyelot match beats smaller mismatched roll');
ok(pinned.results.find(x=>x.roll==='OTHER').reason==='DYELOT_MISMATCH','mismatched dyelot flagged');
ok(pinned.results.find(x=>x.roll==='UNKNOWN').reason==='DYELOT_UNKNOWN','unknown dyelot flagged');
ok(!pinned.results.find(x=>x.roll==='OTHER').areaCandidate,'mismatched dyelot cannot be recommended');
const inherited=a.advise({style:'Dawn',colour:'Blue',quantity:80,unit:'sf',existingRolls:[{lot:'DL-2'}],items:[roll('MATCH',9,'DL-2'),roll('WRONG',7,'DL-1')]});
ok(inherited.requiredDyelot==='dl 2'&&inherited.results[0].roll==='MATCH','inherit lot from existing roll');
ok(a.advise({style:'Dawn',colour:'Blue',quantity:80,unit:'sf',dyelot:'DL-1',existingRolls:[{lot:'DL-2'}],items:[]}).code==='REQUEST_DYELOT_CONFLICT','conflicting specified lot fail closed');
ok(a.advise({style:'Dawn',colour:'Blue',quantity:80,unit:'sf',existingRolls:[{lot:'DL-1'},{lot:'DL-2'}],items:[]}).code==='EXISTING_DYELOT_CONFLICT','mixed existing lots fail closed');
ok(a.advise({style:'Dawn',colour:'Blue',quantity:80,unit:'sf',existingRolls:[{lot:''}],items:[]}).code==='EXISTING_DYELOT_UNKNOWN','missing existing lot fail closed');
const combos=a.adviseSameLotSets({style:'Dawn',colour:'Blue',quantity:180,unit:'sf',items:[roll('A',8,'DL-1'),roll('B',8,'DL-1'),roll('C',8,'DL-2'),roll('D',8,'DL-2'),roll('E',3,'')]});
ok(combos.ok&&combos.sets.length>=2,'same-lot pairs found');
ok(combos.sets.every(x=>x.rolls.length===2&&x.totalEstimatedSF>=180),'two-roll combinations meet area');
ok(combos.sets.every(x=>x.rolls.every(id=>['A','B'].includes(id))||x.rolls.every(id=>['C','D'].includes(id))),'never mix dyelots');
ok(combos.sets.every(x=>x.cutVerified===false),'combination is not certified cut plan');
console.log('Smart Carpet Advisor V1 LAB: PASS');
