import fs from 'node:fs';
import vm from 'node:vm';
const must=(v,msg)=>{if(!v)throw Error(msg)};
const picker=fs.readFileSync('flooring/smart-inventory-picker-v072.js','utf8');
const bridge=fs.readFileSync('flooring/po-paper-inventory-bridge-v052.js','utf8');
const paper=fs.readFileSync('flooring/deerfoot-po-invoice-paper-edit-v044r7.html','utf8');
new vm.Script(picker);new vm.Script(bridge);
must(/openForRow: \(row,query(?:,options)?\) => openPicker\(row,query\|\|""(?:,options)?\)/.test(picker),'explicit row picker API missing');
must(/api\.openForRow\(row, query(?:, \{)?/.test(bridge),'paper editor does not bind selected row');
must(/id="sip72return">← Return to PO/.test(picker),'return to PO missing');
must(/id="sip72confirm" disabled>Choose a roll above/.test(picker),'sticky selection confirmation missing');
must(/by\("sip72confirm"\)\.addEventListener\("click", useSelected\)/.test(picker),'confirmation click missing');
must(/confirm\.disabled=!item\.selectable/.test(picker),'unavailable inventory confirmation not disabled');
must(/grid-template-rows:auto auto minmax\(0,1fr\) auto/.test(picker),'sticky footer grid row missing');
must(/<\/div><\/div><div class="sip72footer">/.test(picker),'footer must be outside scrollable results');
must(/if\(!\/iPhone\|iPad\|iPod\/i\.test\(navigator\.userAgent/.test(picker),'iOS keyboard focus guard missing');
must(bridge.includes('cell.ownerDocument.defaultView.Event'),'cross-frame event realm guard missing');
must(/smart-inventory-picker-v072\.js\?v=05[34]/.test(paper),'picker script cache not refreshed');
must(/po-paper-inventory-bridge-v052\.js\?v=05[34]/.test(paper),'bridge script cache not refreshed');
must(!/localStorage\.setItem|\.from\(['"]warehouse_records/.test(bridge),'paper bridge must not write inventory');
console.log('PO Paper Inventory Return V0.3.53: PASS');
